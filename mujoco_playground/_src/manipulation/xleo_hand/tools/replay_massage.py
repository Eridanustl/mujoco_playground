"""Replay expert trajectory data on the XLEO dual hand scene.

Loads a pkl file generated by generate_massage_data.py and drives the
simulation using PD torque control for all joints. Records the actual
joint positions/velocities and contact forces during replay, then saves
the recorded data as a new pkl for imitation learning.

Usage:
    python replay_massage.py --pkl_path massage_data.pkl
    python replay_massage.py --pkl_path massage_data.pkl --output replay.pkl
    python replay_massage.py --pkl_path massage_data.pkl --headless
"""

import argparse
import pickle
import signal
from pathlib import Path

import mujoco
import mujoco.viewer
import numpy as np

from mujoco_playground._src.manipulation.xleo_hand import constants as consts


def _project_root() -> Path:
  """Walk up from this file to find the project root (directory containing .git)."""
  p = Path(__file__).resolve().parent
  while p != p.parent:
    if (p / ".git").exists():
      return p
    p = p.parent
  raise RuntimeError("Cannot find project root (no .git found)")


def _interpolate(data: np.ndarray, t: float, data_freq: float) -> np.ndarray:
  """Linearly interpolate a (T, D) array at continuous time t."""
  idx = t * data_freq
  T = data.shape[0]
  i0 = int(idx)
  if i0 >= T - 1:
    return data[-1]
  i1 = i0 + 1
  alpha = idx - i0
  return (1.0 - alpha) * data[i0] + alpha * data[i1]


def run(
    pkl_path: str,
    wrist_kp: float,
    wrist_kd: float,
    finger_kp: float,
    finger_kd: float,
    output: str,
    data_freq: float,
    headless: bool,
):
  with open(pkl_path, "rb") as f:
    traj = pickle.load(f)

  qpos_data = traj["qpos"]  # (T, NQ)
  src_data_freq = traj["data_freq"]
  duration = traj["duration"]

  scene_xml = str(
      _project_root()
      / "mujoco_playground"
      / "_src"
      / "manipulation"
      / "xleo_hand"
      / "models"
      / "xmls"
      / "ftl_xleo_dual_hand.scene.xml"
  )
  model = mujoco.MjModel.from_xml_path(scene_xml)
  data = mujoco.MjData(model)

  # Resolve actuator ctrl indices and joint qpos/qvel addresses.
  act_ids = [model.actuator(n).id for n in consts.ACTUATOR_NAMES]
  qpos_adrs = []
  qvel_adrs = []
  for jname in consts.JOINT_NAMES:
    jid = model.joint(jname).id
    qpos_adrs.append(model.jnt_qposadr[jid])
    qvel_adrs.append(model.jnt_dofadr[jid])

  # Resolve contact force sensor addresses in sensordata.
  sensor_adrs = [
      model.sensor_adr[model.sensor(n).id]
      for n in consts.CONTACT_FORCE_SENSOR_NAMES
  ]

  # Resolve body ids for tracked body xpos and key body xpos.
  tracked_body_ids = [model.body(n).id for n in consts.TRACKED_BODY_NAMES]
  key_body_ids = [model.body(n).id for n in consts.KEY_BODY_NAMES]

  # Per-joint kp/kd: wrist vs finger gains.
  kp = np.zeros(consts.NQ)
  kd = np.zeros(consts.NQ)
  kp[consts.WRIST_INDICES] = wrist_kp
  kd[consts.WRIST_INDICES] = wrist_kd
  kp[consts.FINGER_INDICES] = finger_kp
  kd[consts.FINGER_INDICES] = finger_kd

  # Simulation loop parameters.
  timestep = model.opt.timestep
  total_steps = int(duration / timestep)
  record_interval = max(1, int(round(1.0 / (data_freq * timestep))))

  print(
      f"Simulation: timestep={timestep}, total_steps={total_steps}, "
      f"record every {record_interval} steps, data_freq={data_freq} Hz"
  )
  print(f"Duration: {duration}s, source data_freq: {src_data_freq} Hz")

  # Storage for recorded data.
  rec_qpos = []
  rec_qvel = []
  rec_contact_force = []
  rec_tracked_body_xpos = []
  rec_key_body_xpos = []

  for step_i in range(total_steps):
    t = step_i * timestep

    # PD torque control.
    qpos_target = _interpolate(qpos_data, t % duration, src_data_freq)
    for i in range(consts.NQ):
      q_err = qpos_target[i] - data.qpos[qpos_adrs[i]]
      qvel_actual = data.qvel[qvel_adrs[i]]
      torque = kp[i] * q_err - kd[i] * qvel_actual
      data.ctrl[act_ids[i]] = torque

    # Step physics.
    mujoco.mj_step(model, data)

    # Record at data_freq.
    if step_i % record_interval == 0:
      rec_qpos.append(np.array([data.qpos[a] for a in qpos_adrs]))
      rec_qvel.append(np.array([data.qvel[a] for a in qvel_adrs]))
      rec_contact_force.append(
          np.array(
              [data.sensordata[adr : adr + 3].copy() for adr in sensor_adrs]
          )
      )
      rec_tracked_body_xpos.append(
          np.array([data.xpos[b].copy() for b in tracked_body_ids])
      )
      rec_key_body_xpos.append(
          np.array([data.xpos[b].copy() for b in key_body_ids])
      )

    # Progress.
    if step_i % (total_steps // 10) == 0:
      pct = step_i / total_steps * 100
      print(f"  {pct:.0f}% ({step_i}/{total_steps})")

  rec_qpos = np.array(rec_qpos)  # (T, NQ)
  rec_qvel = np.array(rec_qvel)  # (T, NQ)
  rec_contact_force = np.array(rec_contact_force)  # (T, 6, 3)
  rec_tracked_body_xpos = np.array(rec_tracked_body_xpos)  # (T, 20, 3)
  rec_key_body_xpos = np.array(rec_key_body_xpos)  # (T, 6, 3)
  print(f"rec_tracked_body_xpos.shape: {rec_tracked_body_xpos.shape}")

  # Check cyclic trajectory condition: first frame vs last frame.
  print("\n--- Cyclic trajectory check (|first - last| per joint) ---")
  diff = np.abs(rec_qpos[0] - rec_qpos[-1])
  for i, jname in enumerate(consts.JOINT_NAMES):
    status = "OK" if diff[i] < 0.01 else "WARN"
    print(f"  [{status}] {jname}: diff={diff[i]:.6f}")

  print(
      f"\nRecorded: qpos {rec_qpos.shape}, qvel {rec_qvel.shape}, "
      f"contact_force {rec_contact_force.shape}, "
      f"tracked_body_xpos {rec_tracked_body_xpos.shape}, "
      f"key_body_xpos {rec_key_body_xpos.shape}"
  )

  # Save recorded data.
  output_data = {
      "qpos": rec_qpos,
      "qvel": rec_qvel,
      "contact_force": rec_contact_force,
      "contact_sensor_names": consts.CONTACT_FORCE_SENSOR_NAMES,
      "tracked_body_xpos": rec_tracked_body_xpos,
      "key_body_xpos": rec_key_body_xpos,
      "data_freq": data_freq,
      "duration": duration,
  }

  Path(output).parent.mkdir(parents=True, exist_ok=True)
  with open(output, "wb") as f:
    pickle.dump(output_data, f)
  print(f"Saved to {output}")

  # Optionally launch viewer for visual inspection (non-headless mode).
  if not headless:
    print("Launching viewer for visual inspection (Ctrl+C to exit)...")

    def controller(m, d):
      t = d.time % duration
      qpos_target = _interpolate(qpos_data, t, src_data_freq)
      for i in range(consts.NQ):
        q_err = qpos_target[i] - d.qpos[qpos_adrs[i]]
        qvel_actual = d.qvel[qvel_adrs[i]]
        torque = kp[i] * q_err - kd[i] * qvel_actual
        d.ctrl[act_ids[i]] = torque

    # Reset data for viewer playback.
    data2 = mujoco.MjData(model)
    mujoco.set_mjcb_control(controller)
    signal.signal(signal.SIGINT, signal.SIG_DFL)
    mujoco.viewer.launch(model, data2)


def main():
  parser = argparse.ArgumentParser(
      description="Replay massage expert trajectory and record simulation data"
  )
  default_pkl = str(_project_root() / "data" / "massage_data.pkl")
  default_output = str(_project_root() / "data" / "massage_replay_data.pkl")
  parser.add_argument(
      "--pkl_path",
      type=str,
      default=default_pkl,
      help="Path to trajectory pkl (default: data/massage_data.pkl)",
  )
  parser.add_argument(
      "--output",
      type=str,
      default=default_output,
      help="Output pkl path (default: data/massage_replay_data.pkl)",
  )
  parser.add_argument(
      "--data_freq",
      type=float,
      default=120.0,
      help="Recording frequency in Hz (default: 120.0)",
  )
  parser.add_argument(
      "--headless",
      action="store_true",
      default=False,
      help="Headless mode: record without viewer (default: True)",
  )
  parser.add_argument(
      "--no-headless",
      dest="headless",
      action="store_false",
      help="Disable headless mode: launch viewer after recording",
  )
  parser.add_argument(
      "--wrist_kp",
      type=float,
      default=150.0,
      help="Wrist PD kp (default: 100.0)",
  )
  parser.add_argument(
      "--wrist_kd", type=float, default=5.0, help="Wrist PD kd (default: 5.0)"
  )
  parser.add_argument(
      "--finger_kp", type=float, default=5.0, help="Finger PD kp (default: 5.0)"
  )
  parser.add_argument(
      "--finger_kd", type=float, default=0.1, help="Finger PD kd (default: 0.1)"
  )
  args = parser.parse_args()
  run(
      args.pkl_path,
      args.wrist_kp,
      args.wrist_kd,
      args.finger_kp,
      args.finger_kd,
      args.output,
      args.data_freq,
      args.headless,
  )


if __name__ == "__main__":
  main()
